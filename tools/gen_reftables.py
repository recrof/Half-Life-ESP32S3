#!/usr/bin/env python3
"""Constant tables of the software renderer (ref/soft/r_glblit.c R_BuildBlendMaps), generated
at build time so that they are in flash (rodata) instead of PSRAM: the lighting colormap
(512 kB) and the additive and modulate blending maps (64 kB each).

usage: gen_reftables.py OUT.c
"""
import sys


def MASK(n):
    return (1 << n) - 1


def MOVE_BIT(s, f, t):
    return ((s >> f) & 1) << t


def blend_maps():
    addmap = bytearray(65536)
    modmap = bytearray(65536)
    for r1 in range(8):
        for g1 in range(8):
            for b1 in range(4):
                for r2 in range(8):
                    for g2 in range(8):
                        for b2 in range(4):
                            index1 = r1 << 5 | g1 << 2 | b1
                            index2 = (r2 << 5 | g2 << 2 | b2) << 8
                            r = min(r1 + r2, MASK(3))
                            g = min(g1 + g2, MASK(3))
                            b = min(b1 + b2, MASK(2))
                            addmap[index2 | index1] = r << 5 | g << 2 | b
                            r = r1 * r2 // MASK(3)
                            g = g1 * g2 // MASK(3)
                            b = b1 * b2 // MASK(2)
                            modmap[index2 | index1] = r << 5 | g << 2 | b
    return addmap, modmap


def colormap():
    out = [0] * (32 * 8192)
    for i in range(8192):
        color = i << 3
        m = color >> 8
        j = color & 0xff
        r1 = ((m >> 5) << 2) & MASK(5)
        g1 = ((m >> 2) << 3) & MASK(6)
        b1 = (m << 3) & MASK(5)
        r1 |= MOVE_BIT(j, 5, 1) | MOVE_BIT(j, 2, 0)
        g1 |= MOVE_BIT(j, 7, 2) | MOVE_BIT(j, 4, 1) | MOVE_BIT(j, 1, 0)
        b1 |= MOVE_BIT(j, 6, 2) | MOVE_BIT(j, 3, 1) | MOVE_BIT(j, 0, 0)
        for light in range(32):
            r = r1 * light // 32
            g = g1 * light // 32
            b = b1 * light // 32
            major = (((r >> 2) & MASK(3)) << 5) | (((g >> 3) & MASK(3)) << 2) | ((b >> 3) & MASK(2))
            minor = (MOVE_BIT(r, 1, 5) | MOVE_BIT(r, 0, 2) | MOVE_BIT(g, 2, 7) | MOVE_BIT(g, 1, 4)
                     | MOVE_BIT(g, 0, 1) | MOVE_BIT(b, 2, 6) | MOVE_BIT(b, 1, 3) | MOVE_BIT(b, 0, 0))
            out[light << 13 | i] = major << 8 | (minor & 0xff)
    return out


def write_array(f, decl, values, per_line=32):
    f.write("%s =\n{\n" % decl)
    for i in range(0, len(values), per_line):
        f.write("\t" + ",".join(str(v) for v in values[i:i + per_line]) + ",\n")
    f.write("};\n\n")


def main():
    addmap, modmap = blend_maps()
    with open(sys.argv[1], "w") as f:
        f.write("// generated by tools/gen_reftables.py, do not edit\n")
        f.write("#include <stdint.h>\n\n")
        write_array(f, "const uint16_t r_const_colormap[32 * 8192]", colormap())
        write_array(f, "const uint8_t r_const_addmap[256 * 256]", list(addmap))
        write_array(f, "const uint8_t r_const_modmap[256 * 256]", list(modmap))


if __name__ == "__main__":
    main()
